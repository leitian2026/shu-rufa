    /** 按码点范围生成,跳过没有定义的码点。 */
    private fun cp(vararg ranges: IntRange): List<String> {
        val out = ArrayList<String>()
        for (r in ranges) for (c in r) if (Character.isDefined(c)) out.add(String(Character.toChars(c)))
        return out
    }

